import { derive } from '../../derive'
import type { ConsoleSpec } from '../../../context'
import type { TemplateOptions } from '../../options'

/**
 * The console shell.
 *
 * Deliberately the plain tier: a fixed sidebar and a content area, with no
 * `@octanejs/resizable-panels`, no generated icon sprite and no shared
 * `components/overview` — none of which an arbitrary beast app has. It compiles
 * anywhere, and it is seeded rather than managed, so it is yours to grow.
 */
export const consoleShellPage = (spec: ConsoleSpec, options: TemplateOptions): string => {
  const c = derive(spec, options.appSlug)

  return `// Generated by @beastjs/auth as a starting point. Yours to edit.
import { Link, Outlet } from '@octanejs/tanstack-router'
import { buildAppUrl } from '@/lib/routing/app-url'
import { is${c.pascal}SubdomainHostname, ${c.camel}RoutePrefix } from '@/lib/routing/${c.label}-console'
import '@/styles/${c.label}.css'

setup
  // The console's pages are the same on both hosts: its own subdomain roots them
  // at \`/\`, while the main origin roots them under \`${c.routePrefix}\`, so links have
  // to be built rather than written out.
  const base =
    typeof window !== 'undefined' && !is${c.pascal}SubdomainHostname(window.location.hostname)
      ? ${c.camel}RoutePrefix
      : ''

  const overviewPath = base.length > 0 ? base : '/'

  const homeUrl = typeof window === 'undefined' ? '/' : buildAppUrl(new URL(window.location.href), '/').toString()

main(className='${c.cssPrefix}-frame')
  aside(className='${c.cssPrefix}-sidebar')
    a(className='${c.cssPrefix}-brand' href={homeUrl})
      span(className='${c.cssPrefix}-brand-mark') ${c.title.slice(0, 1)}
      span(className='${c.cssPrefix}-brand-name') ${c.title}
    nav(className='${c.cssPrefix}-nav' aria-label='${c.title}')
      Link(className='${c.cssPrefix}-nav-link' to={overviewPath}) Overview
    p(className='${c.cssPrefix}-sidebar-foot') Back to the app

  section(className='${c.cssPrefix}-content')
    div(className='${c.cssPrefix}-gate' role='status')
      strong Open to everyone.
      span No \`${c.claim}\` session is checked on this console yet.
    Outlet
`
}

